"""Real pictures of the apps for the videos, made by the apps themselves with no window on the screen.

    python ferramentas/capturas.py            # everything missing
    python ferramentas/capturas.py --refazer  # everything again

Writes to public/gerado/ (outside git, regenerated by this script):
  fundos/<example>.mp4      4 s of each Fundo Vivo example, frame by frame from FundoVivo.exe --vivo-still (30 fps)
  fundos/<example>.jpg      the first frame, for stills and the setup's poster
  biblioteca.png            the Fundo Vivo window (--screenshot library), with a sandbox home so only the examples show
  cursores/<variant>/<name>/NNN.png   each animated pointer of ilha-cursors sampled at 30 fps (read from the .ani)
  cursores/<variant>/arrow.png      the static arrow
The Fundo Vivo frames take ~1.5 s each: ~12 minutes the first time.
"""
import json
import os
import shutil
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

from PIL import Image

RAIZ = Path(__file__).resolve().parent.parent
BASE = RAIZ.parent.parent  # the "Claude Code" folder
GERADO = RAIZ / "public" / "gerado"
FV = BASE / "fundo-vivo" / "app" / "FundoVivo.exe"
EXEMPLOS = BASE / "fundo-vivo" / "app" / "examples"
CURSORES = BASE / "ilha-cursors" / "build"
REFAZER = "--refazer" in sys.argv
SEGUNDOS, FPS = 4, 30
# animated pointers shown in the videos (file name in ilha-cursors/build/<variant>/)
ANIMADOS = ["busy", "working", "link", "text", "move", "help", "precision", "unavailable"]


def fundo_vivo_home() -> dict:
    home = Path(tempfile.gettempdir()) / "desktopglow-video-fundovivo"
    (home / "roaming").mkdir(parents=True, exist_ok=True)
    # no Wallpaper Engine library in the pictures: only the app's own examples
    (home / "roaming" / "config.json").write_text(json.dumps({"scanWallpaperEngine": False}), encoding="utf-8")
    return {**os.environ, "FUNDOVIVO_HOME": str(home)}


def fundos():
    pasta = GERADO / "fundos"
    pasta.mkdir(parents=True, exist_ok=True)
    env = fundo_vivo_home()
    for vivo in sorted(EXEMPLOS.glob("*.vivo")):
        mp4 = pasta / f"{vivo.stem}.mp4"
        if mp4.exists() and not REFAZER:
            continue
        quadros = pasta / f"_{vivo.stem}"
        quadros.mkdir(exist_ok=True)
        extra = ["0", "som"]  # a made-up spectrum: the ones that react to sound (pulse, cube, aurora...) show it
        for i in range(SEGUNDOS * FPS):
            png = quadros / f"{i:04d}.png"
            if png.exists():
                continue
            t = f"{3 + i / FPS:.4f}"  # a few seconds in, so particles have spread out
            cmd = [str(FV), "--vivo-still", str(vivo), str(png), "1920", "1080", t, *extra]
            # the WebView2 behind --vivo-still fails now and then on its own (seen at frame 48 of 120): a few tries
            for _tentativa in range(3):
                if subprocess.run(cmd, env=env).returncode == 0 and png.exists():
                    break
            else:
                sys.exit(f"--vivo-still failed three times for {vivo.name} at t={t}")
            if i % 30 == 0:
                print(f"{vivo.stem}: {i}/{SEGUNDOS * FPS}", flush=True)
        shutil.copy(quadros / "0000.png", pasta / f"{vivo.stem}.png")
        Image.open(quadros / "0000.png").convert("RGB").save(pasta / f"{vivo.stem}.jpg", quality=90)
        subprocess.run(["ffmpeg", "-y", "-v", "error", "-framerate", str(FPS), "-i", str(quadros / "%04d.png"),
                        "-c:v", "libx264", "-crf", "14", "-preset", "slow", "-pix_fmt", "yuv420p", str(mp4)], check=True)
        shutil.rmtree(quadros)
        print("ok", mp4.name, flush=True)


def biblioteca():
    png = GERADO / "biblioteca.png"
    if png.exists() and not REFAZER:
        return
    GERADO.mkdir(parents=True, exist_ok=True)
    subprocess.run([str(FV), "--screenshot", str(png), "library", "1500", "940"], env=fundo_vivo_home(), check=True)
    print("ok", png.name)


def cur_frame(data: bytes, want: int = 128) -> Image.Image:
    """The 32-bit frame of a .cur written by ilha-cursors (Pillow drops its alpha)."""
    count = struct.unpack_from("<H", data, 4)[0]
    for i in range(count):
        w, _h, _c, _r, _hx, _hy, _size, offset = struct.unpack_from("<BBBBHHII", data, 6 + 16 * i)
        if (w or 256) != want:
            continue
        width, height2 = struct.unpack_from("<ii", data, offset + 4)
        height = height2 // 2
        pixels = data[offset + 40: offset + 40 + width * height * 4]
        return Image.frombuffer("RGBA", (width, height), pixels, "raw", "BGRA", 0, -1).copy()
    raise ValueError(f"no {want} px frame")


def ani(path: Path):
    """(frames, steps as (frame index, jiffies)) of an .ani written by ilha-cursors."""
    data = path.read_bytes()
    assert data[:4] == b"RIFF" and data[8:12] == b"ACON"
    pos, end = 12, len(data)
    frames, rates, seq, header = [], None, None, None

    def chunks(a, b):
        while a + 8 <= b:
            tag, size = data[a:a + 4], struct.unpack_from("<I", data, a + 4)[0]
            yield tag, a + 8, size
            a += 8 + size + (size & 1)

    for tag, start, size in chunks(pos, end):
        if tag == b"anih":
            header = struct.unpack_from("<9I", data, start)
        elif tag == b"rate":
            rates = list(struct.unpack_from(f"<{size // 4}I", data, start))
        elif tag == b"seq ":
            seq = list(struct.unpack_from(f"<{size // 4}I", data, start))
        elif tag == b"LIST" and data[start:start + 4] == b"fram":
            for t2, s2, z2 in chunks(start + 4, start + size):
                if t2 == b"icon":
                    frames.append(data[s2:s2 + z2])
    steps = header[2]
    seq = seq or list(range(steps))
    rates = rates or [header[7]] * steps
    return frames, list(zip(seq, rates))


def cursores():
    for variant in ("black", "white"):
        destino = GERADO / "cursores" / variant
        destino.mkdir(parents=True, exist_ok=True)
        seta = destino / "arrow.png"
        if REFAZER or not seta.exists():
            cur_frame((CURSORES / variant / "arrow.cur").read_bytes()).save(seta)
        for nome in ANIMADOS:
            pasta = destino / nome
            if pasta.exists() and not REFAZER:
                continue
            pasta.mkdir(exist_ok=True)
            frames, steps = ani(CURSORES / variant / f"{nome}.ani")
            imagens = {}
            # walk the steps in time and take what is on screen every 1/30 s, for 4 s (intro + some loop)
            t_jiffies, i_step, acumulado = 0, 0, 0
            for q in range(SEGUNDOS * FPS):
                t_jiffies = q * 2  # 60 jiffies per second
                while i_step < len(steps) - 1 and acumulado + steps[i_step][1] <= t_jiffies:
                    acumulado += steps[i_step][1]
                    i_step += 1
                idx = steps[i_step][0]
                if idx not in imagens:
                    imagens[idx] = cur_frame(frames[idx])
                imagens[idx].save(pasta / f"{q:03d}.png")
        print("ok cursors", variant)


def anurati():
    # the clock's day font: personal use only, so it is copied here (outside git) from relogio-mond, never committed
    origem = BASE / "relogio-mond" / "fontes" / "Anurati-Regular.otf"
    destino = GERADO / "fontes" / "Anurati-Regular.otf"
    if origem.exists() and (REFAZER or not destino.exists()):
        destino.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy(origem, destino)
    elif not origem.exists():
        print("no Anurati in relogio-mond/fontes (open the clock once): the day falls back to Quicksand")


if __name__ == "__main__":
    # no anurati() since 03/11/2026: the videos are public and the font is for personal use only (Quicksand instead)
    cursores()
    biblioteca()
    fundos()
